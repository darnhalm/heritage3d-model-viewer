/**
 * Бюджет времени теста с поправкой на машину.
 *
 * Раннер GitHub вдвое-втрое медленнее ноутбука: на нём та же сцена грузится дольше, а
 * отрисовка идёт программно. Общий бюджет из конфигурации это уже учитывает, но тесты,
 * которые просят своё время через `test.setTimeout`, конфигурация не перекрывает — они и
 * составляли остаток таймаутов в прогоне.
 *
 * @param ms - Бюджет, которого хватает локально.
 * @returns Тот же бюджет, удвоенный под CI.
 */
export const budget = (ms: number): number => (process.env.CI ? ms * 2 : ms);
